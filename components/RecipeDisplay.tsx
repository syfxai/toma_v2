
import React, { useRef, useState, useEffect } from 'react';
import { toPng } from 'html-to-image';
import jsPDF from 'jspdf';
import type { Recipe, UiText } from '../types';
import FileTextIcon from './icons/FileTextIcon';
import ImageIcon from './icons/ImageIcon';
import WhatsAppIcon from './icons/WhatsAppIcon';
import CheckIcon from './icons/CheckIcon';
import RecipeImageExport from './RecipeImageExport';
import RecipeInfo from './RecipeInfo';
import NutritionDisplay from './NutritionDisplay';
import PriceEstimateDisplay from './PriceEstimateDisplay';

interface RecipeDisplayProps {
  recipe: Recipe;
  uiText: UiText;
}

const RecipeDisplay: React.FC<RecipeDisplayProps> = ({ recipe, uiText }) => {
  const exportImageRefDesktop = useRef<HTMLDivElement>(null);
  const exportImageRefMobile = useRef<HTMLDivElement>(null);
  
  const [isSavingImage, setIsSavingImage] = useState(false);
  const [isSavingPdf, setIsSavingPdf] = useState(false);
  const [checkedIngredients, setCheckedIngredients] = useState<Record<number, boolean>>({});

  useEffect(() => {
    setCheckedIngredients({});
  }, [recipe.recipeName]);

  const toggleIngredient = (index: number) => {
    setCheckedIngredients(prev => ({
      ...prev,
      [index]: !prev[index]
    }));
  };

  const resetCheckedIngredients = () => {
    setCheckedIngredients({});
  };

  const totalIngredients = recipe.ingredients.length;
  const checkedCount = Object.values(checkedIngredients).filter(Boolean).length;

  const handleShareWhatsApp = () => {
    const title = `🛒 *SENARAI BAHAN: ${recipe.recipeName.toUpperCase()}*\n_Disediakan oleh Toma AI_ 🍅\n\n`;
    const details = `👥 *Porsi:* ${recipe.servings || '4 orang'}\n⏱️ *Masa Memasak:* ${recipe.totalTime || recipe.cookTime || '-'}\n\n`;
    const ingredientsHeader = `*Bahan-Bahan Diperlukan:*\n`;
    const ingredientsList = recipe.ingredients.map((item, idx) => {
      const isChecked = checkedIngredients[idx];
      return isChecked ? `✅ ~${item}~` : `▫️ ${item}`;
    }).join('\n');
    const footer = `\n\n👉 _Jana resipi halal anda di: https://toma.syfx.my_`;

    const fullMessage = `${title}${details}${ingredientsHeader}${ingredientsList}${footer}`;
    const url = `https://api.whatsapp.com/send?text=${encodeURIComponent(fullMessage)}`;
    window.open(url, '_blank');
  };

  const formatRecipeAsText = (): string => {
    const title = `RECIPE: ${recipe.recipeName}\n\n`;
    const description = `DESCRIPTION:\n${recipe.description}\n\n`;
    const details = `Prep Time: ${recipe.prepTime}\nCook Time: ${recipe.cookTime}\nTotal Time: ${recipe.totalTime}\nServings: ${recipe.servings}\n\n`;
    const ingredientsHeader = `--------------------\n\n${uiText.recipeIngredients.toUpperCase()}:\n`;
    const ingredientsList = recipe.ingredients.map(i => `- ${i}`).join('\n');
    const instructionsHeader = `\n\n--------------------\n\n${uiText.recipeInstructions.toUpperCase()}:\n`;
    const instructionsList = recipe.instructions.map((step, index) => `${index + 1}. ${step}`).join('\n');
    
    let nutritionText = '';
    if (recipe.nutrition) {
      nutritionText = `\n\n--------------------\n\n${uiText.nutritionTitle.toUpperCase()}:\n`;
      nutritionText += `${uiText.caloriesLabel}: ${recipe.nutrition.calories}\n`;
      nutritionText += `${uiText.proteinLabel}: ${recipe.nutrition.protein}\n`;
      nutritionText += `${uiText.fatLabel}: ${recipe.nutrition.fat}\n`;
      nutritionText += `${uiText.carbsLabel}: ${recipe.nutrition.carbohydrates}\n\n`;
      if (recipe.nutrition.vitamins.length > 0) nutritionText += `${uiText.vitaminsLabel}: ${recipe.nutrition.vitamins.join(', ')}\n`;
      if (recipe.nutrition.minerals.length > 0) nutritionText += `${uiText.mineralsLabel}: ${recipe.nutrition.minerals.join(', ')}\n`;
      if (recipe.nutrition.others.length > 0) nutritionText += `${uiText.othersLabel}: ${recipe.nutrition.others.join(', ')}\n`;
      nutritionText += `\n${recipe.nutrition.healthScore === 'healthy' ? uiText.healthyTip : uiText.unhealthyTip}\n`;
      nutritionText += `\n* ${uiText.nutritionDisclaimer}\n`;
    }

    const footer = `\n\n--------------------\n\nGenerated by Toma AI by Syafiq Haron`;
    return `${title}${description}${details}${ingredientsHeader}${ingredientsList}${instructionsHeader}${instructionsList}${nutritionText}${footer}`;
  };

  const handleDownloadTxt = () => {
    const textContent = formatRecipeAsText();
    const blob = new Blob([textContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `${recipe.recipeName.replace(/\s/g, '_')}_recipe.txt`;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };
  
  const handleDownloadImage = async () => {
    setIsSavingImage(true);
    const isMobile = window.innerWidth < 768;
    const targetRef = isMobile ? exportImageRefMobile : exportImageRefDesktop;

    if (!targetRef.current) {
        setIsSavingImage(false);
        return;
    }

    try {
        const image = await toPng(targetRef.current, {
            pixelRatio: 2,
            backgroundColor: '#ffffff',
            cacheBust: true,
            skipFonts: true,
        });
        const link = document.createElement('a');
        link.href = image;
        link.download = `${recipe.recipeName.replace(/\s/g, '_')}_recipe.png`;
        document.body.appendChild(link);
        link.click();
        document.body.removeChild(link);
    } catch (error) {
        console.error('Error generating canvas:', error);
        alert('Sorry, there was an error creating the image.');
    } finally {
        setIsSavingImage(false);
    }
  };
  
  const handleDownloadPdf = async () => {
    setIsSavingPdf(true);
    // For PDF, we always use the desktop-styled component for a consistent A4 layout.
    const targetRef = exportImageRefDesktop;

    if (!targetRef.current) {
        console.error("PDF export target element not found.");
        setIsSavingPdf(false);
        alert('Could not find the recipe content to create a PDF.');
        return;
    }

    try {
        const imgData = await toPng(targetRef.current, {
            pixelRatio: 2, // Use a higher scale for better resolution in the PDF
            backgroundColor: '#ffffff',
            cacheBust: true,
            skipFonts: true,
        });

        const rect = targetRef.current.getBoundingClientRect();
        const elementWidth = targetRef.current.scrollWidth || rect.width || 800;
        const elementHeight = targetRef.current.scrollHeight || rect.height || 1000;
        
        const pdf = new jsPDF({
            orientation: 'portrait',
            unit: 'mm',
            format: 'a4'
        });

        const pdfWidth = pdf.internal.pageSize.getWidth();
        const pdfHeight = pdf.internal.pageSize.getHeight();
        const margin = 10; // 10mm margin on each side

        const contentWidth = pdfWidth - (margin * 2);
        const contentHeight = pdfHeight - (margin * 2);

        const canvasAspectRatio = elementWidth / elementHeight;

        let finalImgWidth = contentWidth;
        let finalImgHeight = finalImgWidth / canvasAspectRatio;

        // If the image is too tall for the page with the given width,
        // we scale it down based on the page height instead.
        if (finalImgHeight > contentHeight) {
            finalImgHeight = contentHeight;
            finalImgWidth = finalImgHeight * canvasAspectRatio;
        }

        const x = (pdfWidth - finalImgWidth) / 2; // Center horizontally
        const y = (pdfHeight - finalImgHeight) / 2; // Center vertically

        pdf.addImage(imgData, 'PNG', x, y, finalImgWidth, finalImgHeight);
        pdf.save(`${recipe.recipeName.replace(/\s/g, '_')}_recipe.pdf`);

    } catch (error) {
        console.error('Error generating PDF:', error);
        alert('Sorry, there was an error creating the PDF.');
    } finally {
        setIsSavingPdf(false);
    }
  };


  const ExportButton: React.FC<{onClick: () => void, disabled?: boolean, icon: React.ReactNode, text: string}> = ({ onClick, disabled, icon, text }) => (
    <button
      onClick={onClick}
      disabled={disabled}
      className="flex items-center gap-2 px-3 py-2 md:px-4 bg-white/60 backdrop-blur-md border border-white/60 rounded-full shadow-sm text-xs md:text-sm font-medium text-gray-700 hover:bg-white hover:shadow-md focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-emerald-500 transition-all disabled:opacity-50 disabled:cursor-wait whitespace-nowrap"
    >
      {icon}
      <span>{text}</span>
    </button>
  );

  return (
    <>
      {/* Main view - Enhanced Glassmorphism */}
      <div className="max-w-4xl mx-auto mt-8 md:mt-12 bg-white/60 backdrop-blur-xl p-5 md:p-10 rounded-2xl shadow-xl border border-white/40 ring-1 ring-white/50 animate-fadeInUp">
        
        <div className="text-center mb-6 md:mb-8">
          <h2 className="text-2xl sm:text-3xl md:text-4xl font-bold bg-gradient-to-r from-emerald-600 to-teal-500 bg-clip-text text-transparent pb-2">
            {recipe.recipeName}
          </h2>
          <p className="mt-2 text-sm md:text-base text-gray-600 italic max-w-2xl mx-auto">{recipe.description}</p>
        </div>
        
        <RecipeInfo recipe={recipe} uiText={uiText} />
        
        <PriceEstimateDisplay ingredients={recipe.ingredients} servings={recipe.servings} />
        
        <NutritionDisplay nutrition={recipe.nutrition} uiText={uiText} />

        <div className="text-center my-6 md:my-8 py-4 border-y border-gray-200/60">
          <h4 className="text-xs md:text-sm font-bold uppercase text-gray-500 tracking-wider mb-4">{uiText.exportTitle}</h4>
          <div className="flex flex-wrap justify-center items-center gap-2 md:gap-4">
              <ExportButton onClick={handleDownloadTxt} icon={<FileTextIcon className="w-4 h-4 md:w-5 md:h-5 text-emerald-700" />} text={uiText.saveAsText} />
              <ExportButton 
                  onClick={handleDownloadImage}
                  disabled={isSavingImage}
                  icon={<ImageIcon className="w-4 h-4 md:w-5 md:h-5 text-emerald-700" />} 
                  text={isSavingImage ? uiText.saveAsImageSaving : uiText.saveAsImage} 
              />
              <ExportButton 
                onClick={handleDownloadPdf}
                disabled={isSavingPdf}
                icon={<FileTextIcon className="w-4 h-4 md:w-5 md:h-5 text-emerald-700" />} 
                text={isSavingPdf ? uiText.saveAsPdfSaving : uiText.saveAsPdf} 
              />
              <ExportButton 
                onClick={handleShareWhatsApp}
                icon={<WhatsAppIcon className="w-4 h-4 md:w-5 md:h-5 text-emerald-600" />} 
                text="Kongsi ke WhatsApp" 
              />
          </div>
        </div>

        <div className="grid grid-cols-1 md:grid-cols-2 gap-6 md:gap-8">
          <div className="bg-emerald-50/50 p-5 md:p-6 rounded-xl border border-emerald-100/50">
            <div className="flex items-center justify-between mb-3 border-b-2 border-emerald-300 pb-2">
              <h3 className="text-xl md:text-2xl font-semibold text-emerald-800">
                {uiText.recipeIngredients}
              </h3>
              {checkedCount > 0 && (
                <button
                  type="button"
                  onClick={resetCheckedIngredients}
                  className="text-xs text-emerald-700 hover:text-emerald-900 bg-emerald-100/70 hover:bg-emerald-200/80 px-2.5 py-1 rounded-md font-medium transition-colors cursor-pointer"
                >
                  Set Semula ({checkedCount}/{totalIngredients})
                </button>
              )}
            </div>

            {totalIngredients > 0 && (
              <div className="mb-3 px-1">
                <div className="flex justify-between text-xs text-gray-500 mb-1 font-medium">
                  <span>Tandakan bahan yang siap/dibeli</span>
                  <span className="text-emerald-700 font-semibold">{checkedCount}/{totalIngredients} siap</span>
                </div>
                <div className="w-full bg-gray-200/80 rounded-full h-1.5 overflow-hidden">
                  <div 
                    className="bg-emerald-500 h-1.5 rounded-full transition-all duration-300 ease-out"
                    style={{ width: `${(checkedCount / totalIngredients) * 100}%` }}
                  />
                </div>
              </div>
            )}

            <ul className="space-y-1.5 text-sm md:text-base">
              {recipe.ingredients.map((ingredient, index) => {
                const isChecked = !!checkedIngredients[index];
                return (
                  <li 
                    key={index}
                    onClick={() => toggleIngredient(index)}
                    className={`flex items-start gap-2.5 p-2 rounded-lg cursor-pointer transition-all duration-150 select-none ${
                      isChecked 
                        ? 'bg-emerald-100/50 text-gray-400 line-through' 
                        : 'hover:bg-white/80 text-gray-700'
                    }`}
                  >
                    <span className={`mt-0.5 flex-shrink-0 w-4 h-4 rounded-full border flex items-center justify-center transition-all ${
                      isChecked 
                        ? 'bg-emerald-600 border-emerald-600 text-white shadow-sm' 
                        : 'border-gray-300 hover:border-emerald-500 bg-white'
                    }`}>
                      {isChecked && <CheckIcon className="w-3 h-3 stroke-[3]" />}
                    </span>
                    <span className="leading-snug">{ingredient}</span>
                  </li>
                );
              })}
            </ul>
          </div>
          
          <div className="bg-emerald-50/50 p-5 md:p-6 rounded-xl border border-emerald-100/50 animate-fadeInUp">
            <h3 className="text-xl md:text-2xl font-semibold mb-4 border-b-2 border-emerald-300 pb-2 text-emerald-800">{uiText.recipeInstructions}</h3>
            <ol className="list-decimal list-outside space-y-3 md:space-y-4 text-gray-700 leading-relaxed ml-5 text-sm md:text-base">
              {recipe.instructions.map((step, index) => (
                <li key={index}>{step}</li>
              ))}
            </ol>
          </div>
        </div>
      </div>
      
      {/* Hidden components for clean exports */}
      <div className="absolute -left-[9999px] -top-[9999px]">
        {/* Pass the generated image to the export component so it gets included */}
        <RecipeImageExport 
            recipe={recipe} 
            ref={exportImageRefDesktop} 
            layout="desktop" 
            uiText={uiText} 
        />
        <RecipeImageExport 
            recipe={recipe} 
            ref={exportImageRefMobile} 
            layout="mobile" 
            uiText={uiText} 
        />
      </div>
    </>
  );
};

export default RecipeDisplay;